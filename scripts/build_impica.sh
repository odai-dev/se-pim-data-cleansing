#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=scripts/_common.sh
source "$SCRIPT_DIR/_common.sh"

LOG_FILE=$(setup_log "$ROOT_DIR/logs/build" "build_impica")
start_logging "$LOG_FILE"

PIM_DEVICE=${PIM_DEVICE:-hash_table}
DEFAULT_JOBS=$(nproc)
if (( DEFAULT_JOBS > 4 )); then
  DEFAULT_JOBS=4
fi
JOBS=${JOBS:-$DEFAULT_JOBS}
M5_NO_WERROR=${M5_NO_WERROR:-1}
IMPICA_DIR="$ROOT_DIR/IMPICA"
GEM5_DIR="$IMPICA_DIR/gem5"
DRIVER_DIR="$IMPICA_DIR/pim_driver"
TARGET_BIN="$GEM5_DIR/build/ARM/gem5.opt"
BUILD_DIR="$GEM5_DIR/build/ARM"
KERNEL_DIR="$IMPICA_DIR/linux-aarch64-gem5-20140821"
KERNEL_ARCH=${KERNEL_ARCH:-arm64}
CROSS_COMPILE=${CROSS_COMPILE:-aarch64-linux-gnu-}

ensure_kernel_compiler_header() {
  local cc_bin="$1"
  local kernel_dir="$2"
  local cc_path major header fallback

  cc_path=$(command -v "$cc_bin" 2>/dev/null || true)
  if [[ -z "$cc_path" ]]; then
    return 0
  fi

  major=$("$cc_bin" -dumpversion 2>/dev/null | sed -E 's/^([0-9]+).*/\1/')
  if [[ -z "$major" ]]; then
    return 0
  fi

  header="$kernel_dir/include/linux/compiler-gcc${major}.h"
  if [[ -f "$header" ]]; then
    return 0
  fi

  for candidate in \
    "$kernel_dir/include/linux/compiler-gcc4.h" \
    "$kernel_dir/include/linux/compiler-gcc3.h"
  do
    if [[ -f "$candidate" ]]; then
      fallback="$candidate"
      break
    fi
  done

  if [[ -z "${fallback:-}" ]]; then
    return 0
  fi

  echo "[INFO] Creating legacy kernel GCC compatibility header: $(basename "$header") -> $(basename "$fallback")"
  cat > "$header" <<EOF
/* Auto-generated by scripts/build_impica.sh for legacy kernel compatibility. */
#include <linux/$(basename "$fallback")>
EOF
}

if [[ ! -d "$IMPICA_DIR" ]]; then
  "$SCRIPT_DIR/bootstrap_repo.sh"
fi

if [[ ! -d "$GEM5_DIR" ]]; then
  fail_gate "GATE 2" "Missing gem5 directory at $GEM5_DIR" "$LOG_FILE"
  exit 1
fi

# Interrupted legacy builds can leave corrupt/truncated object files that
# later fail at link time (e.g., undefined .LASF* in debug_info). If there
# is a partial build tree without the final binary, rebuild from a clean ARM
# build directory for determinism.
if [[ -d "$BUILD_DIR" && ! -x "$TARGET_BIN" ]]; then
  echo "[INFO] Detected partial ARM build tree without gem5.opt; cleaning $BUILD_DIR"
  rm -rf "$BUILD_DIR"
fi

echo "[INFO] Building gem5 (PIM_DEVICE=$PIM_DEVICE, jobs=$JOBS)"
echo "[INFO] Warnings are expected on this legacy tree; build can take a long time."
if ! (
  cd "$GEM5_DIR"
  PYTHONDONTWRITEBYTECODE=1 M5_NO_WERROR="$M5_NO_WERROR" scons -j"$JOBS" "PIM_DEVICE=$PIM_DEVICE" build/ARM/gem5.opt
); then
  fail_gate "GATE 2" "gem5 build failed" "$LOG_FILE"
  exit 1
fi

if [[ ! -x "$TARGET_BIN" ]]; then
  fail_gate "GATE 2" "Expected gem5 binary not found: $TARGET_BIN" "$LOG_FILE"
  exit 1
fi

echo "[INFO] Building pim_driver"
# Prepare kernel headers/config expected by out-of-tree module build.
echo "[INFO] Ensuring kernel tree is prepared for module build"
ensure_kernel_compiler_header gcc "$KERNEL_DIR"
ensure_kernel_compiler_header "${CROSS_COMPILE}gcc" "$KERNEL_DIR"
if ! (
  cd "$KERNEL_DIR"
  if [[ ! -f .config || \
        ! -f include/generated/autoconf.h || \
        ! -f include/config/auto.conf ]]; then
    make ARCH="$KERNEL_ARCH" CROSS_COMPILE="$CROSS_COMPILE" gem5_defconfig
    yes "" | make ARCH="$KERNEL_ARCH" CROSS_COMPILE="$CROSS_COMPILE" oldconfig
  fi
  make -j"$JOBS" ARCH="$KERNEL_ARCH" CROSS_COMPILE="$CROSS_COMPILE" prepare modules_prepare
); then
  fail_gate "GATE 2" "kernel tree preparation failed for pim_driver" "$LOG_FILE"
  exit 1
fi

if ! (
  cd "$DRIVER_DIR"
  make ARCH="$KERNEL_ARCH" CROSS_COMPILE="$CROSS_COMPILE"
); then
  fail_gate "GATE 2" "pim_driver build failed (likely missing kernel build prerequisites/artifacts)" "$LOG_FILE"
  exit 1
fi

echo "[PASS] GATE 2 build artifacts produced"
